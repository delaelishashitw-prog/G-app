export function getTodayDevotional(customDate?: Date): DevotionalItem {
  const date = customDate || new Date();
  const day = date.getDate(); // 1 - 31
  const found = DEVOTIONAL_ARCHIVE.find((d) => d.dayOfMonth === day);
  return found || DEVOTIONAL_ARCHIVE[0];
}

export function getDevotionalById(id: string): DevotionalItem | undefined {
  return DEVOTIONAL_ARCHIVE.find((d) => d.id === id);
}

export function getRandomDevotional(excludeId?: string): DevotionalItem {
  const pool = excludeId
    ? DEVOTIONAL_ARCHIVE.filter((d) => d.id !== excludeId)
    : DEVOTIONAL_ARCHIVE;
  const index = Math.floor(Math.random() * pool.length);
  return pool[index] || DEVOTIONAL_ARCHIVE[0];
}
