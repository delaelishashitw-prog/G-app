import fs from 'node:fs';
import path from 'node:path';
const migrations='supabase/migrations';
const files=fs.readdirSync(migrations).filter(file=>file.endsWith('.sql')).sort();
const upgradeFiles=files.filter(file=>file.startsWith('20261015'));
const schema=files.map(file=>`-- ${file}\n${fs.readFileSync(path.join(migrations,file),'utf8')}`).join('\n\n');
const upgrade=upgradeFiles.map(file=>fs.readFileSync(path.join(migrations,file),'utf8')).join('\n\n');
const source=`// Generated by npm run generate:sql. Do not hand-edit permission repair scripts.\nexport const SQL_MIGRATION_SCHEMA = ${JSON.stringify('BEGIN;\n'+schema+'\nCOMMIT;')};\nexport const SQL_FIX_RLS_SCHEMA = ${JSON.stringify('BEGIN;\n'+upgrade+'\nCOMMIT;')};\nexport const SQL_FIX_CHURCH_FINANCE_SCHEMA = SQL_FIX_RLS_SCHEMA;\nexport const SQL_FIX_WELFARE_SCHEMA = SQL_FIX_RLS_SCHEMA;\nexport const SQL_FIX_ROSTER_SCHEMA = SQL_FIX_RLS_SCHEMA;\n`;
fs.writeFileSync('src/lib/supabaseSchema.ts',source);
